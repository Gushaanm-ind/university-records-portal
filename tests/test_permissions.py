ROLE_USER = {
    "student": "101",
    "teacher": "T001",
    "hod": "hod",
    "admin": "admin",
}

CASE_IDS = [f"{r}-{m}-{p}" for r, p, m, _e, _d in TEST_CASES]


@pytest.mark.parametrize("role,path,method,expected,desc", TEST_CASES, ids=CASE_IDS)
def test_permission_matrix(app, db_file, role, path, method, expected, desc):
    client = app.test_client()
    if role != "anonymous":
        client.post("/login", data={"username": ROLE_USER[role],
                                    "password": "testpass123!"})
    resp = client.get(path) if method == "GET" else client.post(path)
    assert resp.status_code == expected, (
        f"{role} {method} {path}: expected {expected}, got {resp.status_code} ({desc})"
    )
